-- Shop schema (normalized to 3NF). Works on PostgreSQL and on H2 in PostgreSQL mode.

create table category (
    id        bigint generated by default as identity primary key,
    name      varchar(50) not null unique,
    parent_id bigint references category (id)              -- self reference: category tree
);

create table product (
    id          bigint generated by default as identity primary key,
    name        varchar(100)   not null unique,
    category_id bigint         not null references category (id),
    price       numeric(10, 2) not null check (price >= 0),
    stock       int            not null default 0 check (stock >= 0)
);

create table customer (
    id    bigint generated by default as identity primary key,
    email varchar(100) not null unique,
    name  varchar(100) not null,
    city  varchar(50)                                       -- nullable on purpose (NULL exercises)
);

create table orders (                                       -- "order" is a reserved word
    id          bigint generated by default as identity primary key,
    customer_id bigint      not null references customer (id),
    ordered_on  date        not null,
    status      varchar(20) not null default 'NEW' check (status in ('NEW', 'PAID', 'SHIPPED', 'CANCELLED'))
);

create table order_item (
    order_id   bigint         not null references orders (id) on delete cascade,
    product_id bigint         not null references product (id),
    quantity   int            not null check (quantity > 0),
    unit_price numeric(10, 2) not null,                     -- price at the time of the order (history!)
    primary key (order_id, product_id)                      -- composite key
);

-- index for "orders of a customer in a date range" (leftmost column = customer_id)
create index idx_orders_customer_date on orders (customer_id, ordered_on);
-- foreign keys used in joins
create index idx_product_category on product (category_id);
create index idx_order_item_product on order_item (product_id);
