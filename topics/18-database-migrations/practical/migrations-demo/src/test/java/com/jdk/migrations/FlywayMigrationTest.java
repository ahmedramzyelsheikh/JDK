package com.jdk.migrations;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.UUID;
import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.MigrationInfo;
import org.flywaydb.core.api.output.MigrateResult;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class FlywayMigrationTest {

    String url;
    Connection keepAlive;

    @BeforeEach
    void freshDatabase() throws SQLException {
        url = "jdbc:h2:mem:fw" + UUID.randomUUID().toString().replace("-", "") + ";DB_CLOSE_DELAY=-1";
        keepAlive = DriverManager.getConnection(url, "sa", "");
    }

    @AfterEach
    void close() throws SQLException {
        keepAlive.close();
    }

    private Flyway flyway(String... locations) {
        return Flyway.configure()
                .dataSource(url, "sa", "")
                .locations(locations.length == 0 ? new String[] {"classpath:db/migration"} : locations)
                .load();
    }

    private List<String> rows(String sql) throws SQLException {
        try (Statement st = keepAlive.createStatement(); ResultSet rs = st.executeQuery(sql)) {
            List<String> out = new ArrayList<>();
            int cols = rs.getMetaData().getColumnCount();
            while (rs.next()) {
                StringBuilder sb = new StringBuilder();
                for (int i = 1; i <= cols; i++) {
                    sb.append(i > 1 ? " | " : "").append(rs.getString(i));
                }
                out.add(sb.toString());
            }
            return out;
        }
    }

    @Test
    void migratesAFreshDatabaseInVersionOrder() throws SQLException {
        MigrateResult result = flyway().migrate();

        assertThat(result.migrationsExecuted).isEqualTo(6);                     // V1-V4 SQL, V5 Java, R view
        assertThat(result.targetSchemaVersion).isEqualTo("5");
        // Flyway creates its table with quoted lower-case identifiers, so they must be quoted in H2
        assertThat(rows("select \"version\", \"description\", \"type\" from \"flyway_schema_history\" order by \"installed_rank\""))
                .containsExactly(
                        "null | << Flyway Schema History table created >> | TABLE",     // bookkeeping row (Flyway 12)
                        "1 | create customer | SQL",
                        "2 | create orders | SQL",
                        "3 | add customer phone | SQL",
                        "4 | expand split customer name | SQL",
                        "5 | Seed countries | JDBC",
                        "null | customer summary view | SQL");
    }

    @Test
    void expandMigrationBackfilledTheNewColumnsAndKeptTheOldOne() throws SQLException {
        flyway().migrate();

        assertThat(rows("select name, first_name, last_name from customer order by id"))
                .containsExactly("Ali Hassan | Ali | Hassan", "Sara Mostafa | Sara | Mostafa");
        assertThat(rows("select first_name, order_count from customer_summary order by id"))
                .containsExactly("Ali | 0", "Sara | 0");
        assertThat(rows("select count(*) from country")).containsExactly("3");
    }

    @Test
    void secondRunAppliesNothing() {
        flyway().migrate();

        MigrateResult again = flyway().migrate();

        assertThat(again.migrationsExecuted).isZero();
        assertThat(Arrays.stream(flyway().info().pending())).isEmpty();
    }

    @Test
    void editingAnAppliedMigrationIsDetectedByChecksum() {
        flyway().migrate();

        Flyway tampered = Flyway.configure()
                .dataSource(url, "sa", "")
                .locations("classpath:db/tampered")
                .ignoreMigrationPatterns("*:missing")                     // V2..V5 aren't in this folder, ignore that
                .load();

        assertThatThrownBy(tampered::validate)
                .hasMessageContaining("checksum mismatch")
                .hasMessageContaining("1");
    }

    @Test
    void baselineAdoptsAnExistingDatabase() throws SQLException {
        try (Statement st = keepAlive.createStatement()) {                  // a "legacy" database created by hand
            st.execute("create table customer (id bigint generated by default as identity primary key, "
                    + "email varchar(100) not null unique, name varchar(100) not null)");
            st.execute("create table orders (id bigint generated by default as identity primary key, "
                    + "customer_id bigint not null references customer (id), status varchar(20) not null default 'NEW', "
                    + "created_at timestamp not null default current_timestamp)");
        }

        MigrateResult result = Flyway.configure().dataSource(url, "sa", "")
                .baselineOnMigrate(true).baselineVersion("2")              // "this DB already is at version 2"
                .load().migrate();

        MigrationInfo[] applied = flyway().info().applied();
        assertThat(applied[0].getDescription()).isEqualTo("<< Flyway Baseline >>");
        assertThat(result.migrationsExecuted).isEqualTo(4);                 // only V3, V4, V5 and R ran
        assertThat(rows("select count(*) from customer")).containsExactly("0");   // V1's inserts did NOT run
    }

    @Test
    void cleanIsDisabledByDefault() {
        flyway().migrate();

        assertThatThrownBy(() -> flyway().clean())                          // would drop every object
                .hasMessageContaining("clean");
    }
}
