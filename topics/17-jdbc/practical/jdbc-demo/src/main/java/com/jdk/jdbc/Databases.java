package com.jdk.jdbc;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;

/** Creates pooled in-memory databases with the demo schema. */
public final class Databases {

    private Databases() {
    }

    public static HikariDataSource pooled(int maxPoolSize) {
        HikariConfig config = new HikariConfig();
        config.setJdbcUrl("jdbc:h2:mem:jdbc" + UUID.randomUUID().toString().replace("-", "") + ";DB_CLOSE_DELAY=-1");
        config.setUsername("sa");
        config.setPassword("");
        config.setMaximumPoolSize(maxPoolSize);
        config.setMinimumIdle(1);
        config.setConnectionTimeout(500);              // ms to wait for a free connection (default 30 s)
        config.setPoolName("demo-pool");
        HikariDataSource ds = new HikariDataSource(config);
        createSchema(ds);
        return ds;
    }

    static void createSchema(HikariDataSource ds) {
        try (Connection c = ds.getConnection(); Statement st = c.createStatement()) {
            st.execute("""
                    create table product (
                        id          bigint generated by default as identity primary key,
                        name        varchar(100) not null unique,
                        price       numeric(10, 2) not null,
                        stock       int,                                -- nullable on purpose
                        released_on date
                    )""");
            st.execute("""
                    create table account (
                        id      varchar(20) primary key,
                        owner   varchar(50) not null,
                        balance numeric(12, 2) not null
                    )""");
            st.execute("insert into account values ('ACC-1', 'Ali', 500.00)");
            st.execute("insert into account values ('ACC-2', 'Sara', 100.00)");
        } catch (SQLException e) {
            throw new IllegalStateException(e);
        }
    }
}
